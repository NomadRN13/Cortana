// RSVPlay — one palette, one file.
//
//   node scripts/build-tokens.js           write brand/tokens.json from mobile/src/theme.js
//   node scripts/build-tokens.js --check   fail if tokens.json is stale, or if the prototype,
//                                          the landing page or the moderation desk disagree
//
// The app's theme (mobile/src/theme.js) is the source. brand/tokens.json is what
// everything else — the Design canvases, print work, anyone outside the repo —
// reads. The check is part of scripts/healthcheck.sh, so the five places the
// palette lives can no longer drift apart silently.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');

const theme = read('mobile/src/theme.js');
const block = /export const colors = \{([\s\S]*?)\};/.exec(theme);
if (!block) { console.error('could not find `export const colors` in mobile/src/theme.js'); process.exit(1); }
const app = {};
for (const m of block[1].matchAll(/(\w+):\s*'([^']+)'/g)) app[m[1]] = m[2];

const tokens = {
  $schema: 'RSVPlay brand tokens. Generated by scripts/build-tokens.js from mobile/src/theme.js; do not edit by hand.',
  color: {
    ink: { value: app.night, use: 'Ground on dark surfaces; text on light surfaces' },
    court: { value: app.text, use: 'Light ground; text on dark surfaces' },
    optic: { value: app.optic, use: 'The one accent: primary actions, active states' },
    courtBlue: { value: '#2F5BFF', use: 'Secondary accent: event headers, avatars' },
    surface: { value: app.card, use: 'Cards on Ink' },
    surface2: { value: app.card2, use: 'Chips and date boxes inside cards' },
    panel: { value: app.panel, use: 'Tab bars and sheets' },
    line: { value: '#2E323B', use: 'Card borders (solid equivalent of the app\'s 13% Court line)' },
    lineStrong: { value: '#3E434E', use: 'Inputs and outlined buttons' },
    muted: { value: '#C9CBD2', use: 'Secondary text on dark (solid equivalent of 62% Court)' },
    success: { value: app.ok, use: 'Verified badges, confirmations' },
    danger: { value: app.danger, use: 'Destructive and negative actions only' },
  },
  alpha: { line: app.line, dim: app.dim, opticDim: app.opticDim },
  font: {
    headline: { family: 'Space Grotesk', weight: 700, tracking: '-0.02em' },
    body: { family: 'Inter', weights: [400, 500, 600, 700] },
  },
  radius: { card: 16, cardLarge: 20, pill: 22, button: 27 },
  app,
};
const out = JSON.stringify(tokens, null, 2) + '\n';
const file = path.join(root, 'brand/tokens.json');

if (!process.argv.includes('--check')) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, out);
  console.log('wrote brand/tokens.json');
  process.exit(0);
}

const problems = [];
if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) problems.push('brand/tokens.json is stale — run node scripts/build-tokens.js');

// Each surface's :root must carry the same values for the names it shares.
const norm = (v) => v.replace(/\s+/g, '').toLowerCase();
function rootVars(rel) {
  const m = /:root\s*\{([\s\S]*?)\}/.exec(read(rel));
  const vars = {};
  if (m) for (const v of m[1].matchAll(/--([\w-]+):\s*([^;]+);/g)) vars[v[1]] = v[2].trim();
  return vars;
}
const expect = {
  'app/index.html': { night: app.night, panel: app.panel, card: app.card, card2: app.card2, line: app.line, text: app.text, dim: app.dim, optic: app.optic, 'optic-dim': app.opticDim, ok: app.ok, ink: app.ink },
  'admin/index.html': { night: app.night, panel: app.panel, card: app.card, card2: app.card2, optic: app.optic, text: app.text, dim: app.dim, line: app.line, ok: app.ok, danger: app.danger, ink: app.ink },
  'landing/index.html': { court: app.night, ink: app.ink, chalk: app.text, optic: app.optic, 'chalk-dim': app.dim },
};
for (const [rel, want] of Object.entries(expect)) {
  const have = rootVars(rel);
  for (const [name, value] of Object.entries(want)) {
    if (!(name in have)) problems.push(`${rel}: --${name} is missing`);
    else if (norm(have[name]) !== norm(value)) problems.push(`${rel}: --${name} is ${have[name]}, the app theme says ${value}`);
  }
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
console.log('tokens agree across the app theme, tokens.json, the prototype, the landing page and the desk');
